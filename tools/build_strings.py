#!/usr/bin/env python3
"""Generates FITNA/Resources/ar.lproj/Localizable.strings from tools/strings_ar.py
and verifies every localization key referenced in Swift exists (exit 1 if not)."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from strings_ar import STRINGS

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

out = os.path.join(ROOT, "FITNA", "Resources", "ar.lproj", "Localizable.strings")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build_strings.py from tools/strings_ar.py — do not edit by hand. */\n\n")
    for k in sorted(STRINGS):
        f.write(f'"{esc(k)}" = "{esc(STRINGS[k])}";\n')

# Static keys used in Swift: L("key" ...)
used = set()
for dirpath, _, files in os.walk(os.path.join(ROOT, "FITNA")):
    for fn in files:
        if fn.endswith(".swift"):
            src = open(os.path.join(dirpath, fn), encoding="utf-8").read()
            used |= set(re.findall(r'\bL\("([A-Za-z0-9_.]+)"', src))
            # keys passed through ternaries / arrays: "xxx.yyy" literals that look like keys
            used |= set(k for k in re.findall(r'"([a-z][A-Za-z0-9]*\.[A-Za-z0-9_.]+)"', src)
                        if k.split(".")[0] in {"color", "sort", "bt2", "progress", "tutorial", "home", "results"} and "%" not in k)

# Dynamic key families generated from enums.
games = ["numberMemory","missingObject","cardMatching","oddOneOut","stroopChallenge","ballTracking",
         "patternCompletion","balanceLogic","missingNumber","mentalMath","valueComparison","sortingChallenge"]
skills = ["memory","attention","logic","speed","math"]
achs = ["smartStart","ironMemory","quickWitted","weekOfChallenge","unstoppableMind","firstWorkout","explorer",
        "firstAssessment","sharpAttention","logician","mathWhiz","threeDayStreak","risingMind","highScorer","spanEight"]
for g in games:
    used |= {f"game.{g}.name", f"game.{g}.tutorial", f"game.{g}.hint"}
for s in skills:
    used |= {f"skill.{s}", f"skill.{s}.desc"}
for i in range(6):
    used |= {f"tier.{i}.name", f"tier.{i}.desc"}
for a in achs:
    used |= {f"ach.{a}.title", f"ach.{a}.detail"}
used |= {f"color.{c}" for c in ["red","blue","green","yellow","purple","orange","turquoise","coral"]}
used |= {f"sort.rule.{r}" for r in ["ascending","descending","alphabetical","alternatingColors"]}
used |= {f"balance.q.{q}" for q in ["heaviest","lightest","secondHeaviest"]}
used |= {f"obj.{o}" for o in ["carrot","ball","box","bell","star","heart","book","cup"]}
used |= {f"progress.range.{r}" for r in ["week","month","all"]}
used |= {f"progress.chart.period.{r}" for r in ["week","month","all"]}

missing = sorted(k for k in used if k not in STRINGS)
unused = sorted(k for k in STRINGS if k not in used)
print(f"{len(STRINGS)} strings written; {len(used)} keys referenced.")
if unused:
    print("Unreferenced (ok, informational):", ", ".join(unused))
if missing:
    print("MISSING KEYS:", ", ".join(missing))
    sys.exit(1)
